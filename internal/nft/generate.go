package nft

import (
	"fmt"
	"net/netip"
	"strings"
)

// Table is the one table LiteNode uses, shared by the firewall and port
// forwarding (DESIGN sections 11 and 14).
const Table = "inet litenode"

// Rule opens ports in the input chain.
type Rule struct {
	// Ports is one port or a range, e.g. "443" or "10000-10100".
	Ports string
	// Proto is "tcp", "udp" or "tcp+udp".
	Proto string
	// Sources limit who may connect (IPv4 / IPv6 addresses or networks);
	// empty means anyone.
	Sources []string
	// Comment names the owner, e.g. "litenode:node:3"; it lets "check and
	// repair" match rules (D-070).
	Comment string
}

// Firewall is the input filter; nil means the firewall is off.
type Firewall struct {
	Rules     []Rule
	BlockPing bool
}

// Config is everything in the table. Forwarding (M4) is added by its
// task.
type Config struct {
	Firewall *Firewall
}

// Empty reports whether the table has nothing to do and is removed.
func (c Config) Empty() bool { return c.Firewall == nil }

// Generate returns the nft script for c. It always first creates and
// deletes the table, so loading it replaces the old table in one
// transaction (or just removes it when c is empty).
func Generate(c Config) ([]byte, error) {
	var b strings.Builder
	b.WriteString("#!/usr/sbin/nft -f\n# Generated by LiteNode from /etc/litenode/state.json; do not edit.\n")
	b.WriteString("table " + Table + "\ndelete table " + Table + "\n")
	if c.Empty() {
		return []byte(b.String()), nil
	}
	b.WriteString("\ntable " + Table + " {\n")
	if f := c.Firewall; f != nil {
		lines, err := inputRules(f)
		if err != nil {
			return nil, err
		}
		b.WriteString("\tchain input {\n\t\ttype filter hook input priority filter; policy drop;\n")
		for _, l := range lines {
			b.WriteString("\t\t" + l + "\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

// base are the rules every firewall needs before the open ports (D-070):
// replies, loopback, IPv6 neighbor discovery and router advertisements
// (without them IPv6 stops working), and DHCP / DHCPv6 replies (without
// them a VPS on DHCP loses its address when the lease ends).
var base = []string{
	"ct state established,related accept",
	"ct state invalid drop",
	`iif "lo" accept`,
	"icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert, mld-listener-query } accept",
	"udp sport 67 udp dport 68 accept",
	"ip6 saddr fe80::/10 udp sport 547 udp dport 546 accept",
}

func inputRules(f *Firewall) ([]string, error) {
	lines := append([]string{}, base...)
	if !f.BlockPing {
		lines = append(lines, "icmp type echo-request accept", "icmpv6 type echo-request accept")
	}
	for _, r := range f.Rules {
		rs, err := ruleLines(r)
		if err != nil {
			return nil, err
		}
		lines = append(lines, rs...)
	}
	return lines, nil
}

// ruleLines writes one rule: one line without sources, otherwise one per
// address family that has sources.
func ruleLines(r Rule) ([]string, error) {
	match, err := portMatch(r.Proto, r.Ports)
	if err != nil {
		return nil, err
	}
	tail := match + " accept"
	if r.Comment != "" {
		tail += fmt.Sprintf(" comment %q", r.Comment)
	}
	if len(r.Sources) == 0 {
		return []string{tail}, nil
	}
	var v4, v6 []string
	for _, s := range r.Sources {
		p, err := ParseSource(s)
		if err != nil {
			return nil, err
		}
		if p.Addr().Is4() {
			v4 = append(v4, sourceString(p))
		} else {
			v6 = append(v6, sourceString(p))
		}
	}
	var out []string
	if len(v4) > 0 {
		out = append(out, "ip saddr { "+strings.Join(v4, ", ")+" } "+tail)
	}
	if len(v6) > 0 {
		out = append(out, "ip6 saddr { "+strings.Join(v6, ", ")+" } "+tail)
	}
	return out, nil
}

func portMatch(proto, ports string) (string, error) {
	if _, _, err := ParsePorts(ports); err != nil {
		return "", err
	}
	switch proto {
	case "tcp", "udp":
		return proto + " dport " + ports, nil
	case "tcp+udp":
		return "meta l4proto { tcp, udp } th dport " + ports, nil
	}
	return "", fmt.Errorf("unknown protocol %q", proto)
}

// ParsePorts reads "443" or "10000-10100".
func ParsePorts(s string) (from, to int, err error) {
	a, b, isRange := strings.Cut(s, "-")
	if from, err = parsePort(a); err != nil {
		return 0, 0, err
	}
	to = from
	if isRange {
		if to, err = parsePort(b); err != nil {
			return 0, 0, err
		}
		if to <= from {
			return 0, 0, fmt.Errorf("port range %q is empty", s)
		}
	}
	return from, to, nil
}

func parsePort(s string) (int, error) {
	var p int
	if _, err := fmt.Sscanf(s, "%d", &p); err != nil || fmt.Sprint(p) != s || p < 1 || p > 65535 {
		return 0, fmt.Errorf("invalid port %q", s)
	}
	return p, nil
}

// ParseSource reads an address or network ("1.2.3.4", "10.0.0.0/8",
// "2001:db8::/32").
func ParseSource(s string) (netip.Prefix, error) {
	if p, err := netip.ParsePrefix(s); err == nil {
		return p.Masked(), nil
	}
	a, err := netip.ParseAddr(s)
	if err != nil {
		return netip.Prefix{}, fmt.Errorf("invalid source %q", s)
	}
	a = a.Unmap()
	return netip.PrefixFrom(a, a.BitLen()), nil
}

func sourceString(p netip.Prefix) string {
	if p.Bits() == p.Addr().BitLen() {
		return p.Addr().String()
	}
	return p.String()
}
