// Package sysctl manages /etc/sysctl.d/99-litenode.conf, the kernel
// settings LiteNode needs: IP forwarding for port forwarding (DESIGN
// section 11), and the system optimizations of M5.
package sysctl

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"slices"
	"strings"

	"github.com/Aspeternity/litenode/internal/change"
	"github.com/Aspeternity/litenode/internal/state"
	"github.com/Aspeternity/litenode/internal/system"
)

// ConfigPath is LiteNode's sysctl file, read last at boot.
const ConfigPath = "/etc/sysctl.d/99-litenode.conf"

// Setting is one "key = value" line.
type Setting struct{ Key, Value string }

// Env is what Desired needs to know about the system.
type Env struct {
	// AcceptRA are the interfaces that take IPv6 router advertisements
	// only while not forwarding (accept_ra = 1).
	AcceptRA []string
}

// Desired lists the settings the state calls for. IPv4 forwarding is on
// while an enabled forward has an IPv4 target, IPv6 forwarding while one
// has an IPv6 target. Turning on IPv6 forwarding makes the kernel ignore
// router advertisements on interfaces with accept_ra = 1, which would
// drop an address or default route learned from them, so those
// interfaces get accept_ra = 2 first (D-075).
func Desired(st *state.State, env Env) []Setting {
	var v4, v6 bool
	for _, f := range st.Forwards {
		if f.Enabled {
			v4 = v4 || f.IPv4() != ""
			v6 = v6 || f.IPv6() != ""
		}
	}
	var out []Setting
	if v4 {
		out = append(out, Setting{"net.ipv4.ip_forward", "1"})
	}
	if v6 {
		ifs := slices.Clone(env.AcceptRA)
		slices.Sort(ifs)
		for _, i := range ifs {
			out = append(out, Setting{interfaceKey(i, "accept_ra"), "2"})
		}
		out = append(out, Setting{"net.ipv6.conf.all.forwarding", "1"})
	}
	return out
}

// interfaceKey names an IPv6 interface setting. Names with dots (VLANs
// such as eth0.100) need the slash form.
func interfaceKey(iface, name string) string {
	if strings.Contains(iface, ".") {
		return "net/ipv6/conf/" + iface + "/" + name
	}
	return "net.ipv6.conf." + iface + "." + name
}

// Generate returns the file for settings.
func Generate(settings []Setting) []byte {
	var b strings.Builder
	b.WriteString("# Generated by LiteNode from /etc/litenode/state.json; do not edit.\n")
	for _, s := range settings {
		b.WriteString(s.Key + " = " + s.Value + "\n")
	}
	return []byte(b.String())
}

// ConfigFile is the change of the sysctl file for settings: removed when
// there are none. ok is false when nothing changes (no settings and no
// file), so the change can leave the kind out.
func ConfigFile(r system.Runner, settings []Setting) (f change.File, ok bool, err error) {
	if len(settings) > 0 {
		return change.File{Path: ConfigPath, Data: Generate(settings), Mode: 0o644}, true, nil
	}
	if _, err := r.ReadFile(ConfigPath); errors.Is(err, fs.ErrNotExist) {
		return change.File{}, false, nil
	} else if err != nil {
		return change.File{}, false, fmt.Errorf("read %s: %w", ConfigPath, err)
	}
	return change.File{Path: ConfigPath, Remove: true}, true, nil
}

// ReadEnv reads the interfaces with accept_ra = 1 (not all, default or
// lo), and those the current file already sets to 2: their value reads 2
// now but must stay in the file for the next boot. A system without IPv6
// has none.
func ReadEnv(r system.Runner) (Env, error) {
	kept := map[string]bool{}
	if data, err := r.ReadFile(ConfigPath); err == nil {
		for _, line := range strings.Split(string(data), "\n") {
			key, _, _ := strings.Cut(line, "=")
			key = strings.ReplaceAll(strings.TrimSpace(key), "/", ".")
			if rest, ok := strings.CutPrefix(key, "net.ipv6.conf."); ok {
				if iface, ok := strings.CutSuffix(rest, ".accept_ra"); ok {
					kept[iface] = true
				}
			}
		}
	}
	const dir = "/proc/sys/net/ipv6/conf"
	entries, err := r.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return Env{}, nil
	}
	if err != nil {
		return Env{}, fmt.Errorf("read %s: %w", dir, err)
	}
	var env Env
	for _, name := range entries {
		if name == "all" || name == "default" || name == "lo" {
			continue
		}
		data, err := r.ReadFile(dir + "/" + name + "/accept_ra")
		if err == nil && (kept[name] || strings.TrimSpace(string(data)) == "1") {
			env.AcceptRA = append(env.AcceptRA, name)
		}
	}
	return env, nil
}

// Kind is the "sysctl" configuration kind. Apply loads the file on disk.
// A removed setting keeps its current value until reboot: other software
// (Docker, VPNs) may rely on forwarding, so LiteNode never turns it off.
func Kind() *change.Kind {
	return &change.Kind{
		Name: "sysctl",
		Apply: func(ctx context.Context, r system.Runner) error {
			if _, err := r.ReadFile(ConfigPath); errors.Is(err, fs.ErrNotExist) {
				return nil
			} else if err != nil {
				return fmt.Errorf("read %s: %w", ConfigPath, err)
			}
			if _, err := r.Exec(ctx, "sysctl", "-p", ConfigPath); err != nil {
				return fmt.Errorf("load %s: %w", ConfigPath, err)
			}
			return nil
		},
	}
}
