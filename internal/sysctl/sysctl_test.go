func TestDesired(t *testing.T) {
	st := state.New()
	env := Env{AcceptRA: []string{"eth1", "eth0.100", "eth0"}}
	if got := Desired(st, env); len(got) != 0 {
		t.Errorf("no forwards: %v", got)
	}
	st.Forwards = []forward.Forward{
		{Enabled: true, TargetHost: "203.0.113.10"},
		{TargetHost: "2001:db8::10"}, // disabled
	}
	if got := Desired(st, env); !slices.Equal(got, []Setting{{"net.ipv4.ip_forward", "1"}}) {
		t.Errorf("IPv4 target: %v", got)
	}
	st.Forwards[1].Enabled = true
	want := "# Generated by LiteNode from /etc/litenode/state.json; do not edit.\n" +
		"net.ipv4.ip_forward = 1\n" +
		"net.ipv6.conf.eth0.accept_ra = 2\n" +
		"net/ipv6/conf/eth0.100/accept_ra = 2\n" +
		"net.ipv6.conf.eth1.accept_ra = 2\n" +
		"net.ipv6.conf.all.forwarding = 1\n"
	if got := string(Generate(Desired(st, env))); got != want {
		t.Errorf("IPv6 target:\n%s", got)
	}
	st.Forwards = nil
	st.Sysopt.BBR = true
	if got := Desired(st, env); !slices.Equal(got, []Setting{{"net.core.default_qdisc", "fq"}, {"net.ipv4.tcp_congestion_control", "bbr"}}) {
		t.Errorf("BBR: %v", got)
	}
}

func TestReadEnv(t *testing.T) {
	f := systemtest.New()
	const dir = "/proc/sys/net/ipv6/conf/"
	for name, v := range map[string]string{"all": "1", "default": "1", "lo": "1", "eth0": "1\n", "ens3": "0", "eth1": "2", "eth0.100": "2"} {
		f.Files[dir+name+"/accept_ra"] = []byte(v)
	}
	// eth0.100 was set to 2 by LiteNode and stays; eth1 by someone else.
	f.Files[ConfigPath] = []byte("net/ipv6/conf/eth0.100/accept_ra = 2\n")
	env, err := ReadEnv(f)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(env.AcceptRA, []string{"eth0", "eth0.100"}) {
		t.Errorf("AcceptRA = %v", env.AcceptRA)
	}
	if env, err := ReadEnv(systemtest.New()); err != nil || len(env.AcceptRA) != 0 {
		t.Errorf("no IPv6: %v %v", env, err)
	}
}

func TestConfigFileAndKind(t *testing.T) {
	ctx := context.Background()
	f := systemtest.New()
	if _, ok, err := ConfigFile(f, nil); ok || err != nil {
		t.Errorf("no settings and no file: ok %v %v", ok, err)
	}
	// Nothing to load without a file.
	if err := Kind().Apply(ctx, f); err != nil || len(f.Execs()) != 0 {
		t.Errorf("Apply without file: %v %v", err, f.Execs())
	}
	file, ok, err := ConfigFile(f, []Setting{{"net.ipv4.ip_forward", "1"}})
	if !ok || err != nil || file.Remove || file.Mode != 0o644 {
		t.Fatalf("ConfigFile = %+v %v %v", file, ok, err)
	}
	f.Files[ConfigPath] = file.Data
	if file, ok, _ := ConfigFile(f, nil); !ok || !file.Remove {
		t.Errorf("last setting gone: %+v %v", file, ok)
	}
	if err := Kind().Apply(ctx, f); err != nil || !slices.Equal(f.Execs(), []string{"sysctl -p " + ConfigPath}) {
		t.Errorf("Apply: %v %v", err, f.Execs())
	}
}

func TestMoveLegacy(t *testing.T) {
	f := systemtest.New()
	if err := MoveLegacy(f); err != nil || len(f.Files) != 0 {
		t.Fatalf("no file: err = %v, files = %v", err, f.Files)
	}
	f.Files[LegacyPath] = []byte("net.ipv4.ip_forward = 1\n")
	if err := MoveLegacy(f); err != nil {
		t.Fatal(err)
	}
	if _, ok := f.Files[LegacyPath]; ok || string(f.Files[ConfigPath]) != "net.ipv4.ip_forward = 1\n" {
		t.Errorf("files = %q", f.Files)
	}
	if len(f.Execs()) != 0 {
		t.Errorf("execs = %q", f.Execs())
	}

	// An interrupted move: the new file wins.
	f.Files[LegacyPath] = []byte("old\n")
	if err := MoveLegacy(f); err != nil {
		t.Fatal(err)
	}
	if _, ok := f.Files[LegacyPath]; ok || string(f.Files[ConfigPath]) != "net.ipv4.ip_forward = 1\n" {
		t.Errorf("both: files = %q", f.Files)
	}
}

// LiteNode's file is read after /etc/sysctl.conf at boot.
func TestConfigPathSortsLast(t *testing.T) {
	f := systemtest.New()
	f.Files["/etc/sysctl.d/99-sysctl.conf"] = []byte("net.ipv4.ip_forward = 0\n")
	f.Files[ConfigPath] = []byte("net.ipv4.ip_forward = 1\n")
	if v, file, _, _ := BootValue(f, "net.ipv4.ip_forward"); v != "1" || file != ConfigPath {
		t.Errorf("got %q from %s", v, file)
	}
}
