const (
	// ResolvConfPath is the resolver configuration of glibc.
	ResolvConfPath = "/etc/resolv.conf"
	// ResolvedDropIn is LiteNode's systemd-resolved configuration.
	ResolvedDropIn = "/etc/systemd/resolved.conf.d/litenode.conf"
	// ResolvedUnit is the systemd-resolved service.
	ResolvedUnit = "systemd-resolved.service"
	// MaxDNSServers is how many servers glibc uses from resolv.conf.
	MaxDNSServers = 3
	// dnsHeader marks files LiteNode wrote.
	dnsHeader = "# Generated by LiteNode; do not edit."
	// dnsProbeName is looked up to test a DNS server.
	dnsProbeName = "www.cloudflare.com"
)

// ErrDNSServers means the server list is empty, too long or not IP
// addresses.
var ErrDNSServers = errors.New("invalid DNS servers")

// DNSPreset is a common public DNS service.
type DNSPreset struct {
	Name    string
	Servers []string
}

// dnsServices are the public DNS services of the DNS menu, with their
// IPv4 and IPv6 addresses.
var dnsServices = []struct {
	name string
	ipv4 [2]string
	ipv6 [2]string
}{
	{"Cloudflare", [2]string{"1.1.1.1", "1.0.0.1"}, [2]string{"2606:4700:4700::1111", "2606:4700:4700::1001"}},
	{"Google", [2]string{"8.8.8.8", "8.8.4.4"}, [2]string{"2001:4860:4860::8888", "2001:4860:4860::8844"}},
	{"Quad9", [2]string{"9.9.9.9", "149.112.112.112"}, [2]string{"2620:fe::fe", "2620:fe::9"}},
}

// PresetsFor returns the DNS menu choices for the exits the machine has
// (D-134): IPv6 addresses only when there is no IPv4 exit, two IPv4 and
// one IPv6 when both work, IPv4 otherwise.
func PresetsFor(ipv4, ipv6 bool) []DNSPreset {
	out := make([]DNSPreset, 0, len(dnsServices))
	for _, d := range dnsServices {
		var servers []string
		switch {
		case ipv6 && !ipv4:
			servers = d.ipv6[:]
		case ipv6:
			servers = []string{d.ipv4[0], d.ipv4[1], d.ipv6[0]}
		default:
			servers = d.ipv4[:]
		}
		out = append(out, DNSPreset{d.name, servers})
	}
	return out
}

// DNS is the DNS state shown in the menu.
type DNS struct {
	// Resolved is true when the system resolves through systemd-resolved:
	// it runs and /etc/resolv.conf points to it.
	Resolved bool
	// Servers are the DNS servers in use.
	Servers []string
	// Managed is true when LiteNode's file sets the servers.
	Managed bool
}

// ParseServers reads a list of IP addresses separated by spaces or
// commas.
func ParseServers(s string) ([]string, error) {
	var out []string
	for _, f := range strings.FieldsFunc(s, func(r rune) bool { return r == ' ' || r == ',' || r == '，' }) {
		a, err := netip.ParseAddr(f)
		if err != nil || a.Zone() != "" {
			return nil, ErrDNSServers
		}
		if s := a.Unmap().String(); !slices.Contains(out, s) {
			out = append(out, s)
		}
	}
	if len(out) == 0 || len(out) > MaxDNSServers {
		return nil, ErrDNSServers
	}
	return out, nil
}

// ResolvedConfig is the systemd-resolved drop-in for servers. "~." makes
// them the servers for all names, ahead of those learned per link (DHCP).
func ResolvedConfig(servers []string) []byte {
	return []byte(dnsHeader + "\n[Resolve]\nDNS=" + strings.Join(servers, " ") + "\nDomains=~.\n")
}

// ResolvConf returns resolv.conf with servers, keeping the search,
// domain and options lines of old.
func ResolvConf(old []byte, servers []string) []byte {
	var b strings.Builder
	b.WriteString(dnsHeader + "\n")
	for _, s := range servers {
		b.WriteString("nameserver " + s + "\n")
	}
	for _, line := range strings.Split(string(old), "\n") {
		if f := strings.Fields(line); len(f) > 0 && (f[0] == "search" || f[0] == "domain" || f[0] == "options") {
			b.WriteString(strings.TrimSpace(line) + "\n")
		}
	}
	return []byte(b.String())
}

// nameservers lists the nameserver lines of a resolv.conf.
func nameservers(data []byte) []string {
	var out []string
	for _, line := range strings.Split(string(data), "\n") {
		if f := strings.Fields(line); len(f) >= 2 && f[0] == "nameserver" {
			out = append(out, f[1])
		}
	}
	return out
}

// resolvedServers reads the DNS= line of the drop-in.
func resolvedServers(data []byte) []string {
	for _, line := range strings.Split(string(data), "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(line), "DNS="); ok {
			return strings.Fields(v)
		}
	}
	return nil
}

// usesResolved reports whether resolv.conf is the file of
// systemd-resolved (its stub or its list of upstream servers).
func usesResolved(resolvConf []byte) bool {
	return strings.Contains(string(resolvConf), "systemd-resolved")
}

// DNSStatus reads the DNS configuration.
// ResolvConfManaged reports whether LiteNode wrote this resolv.conf.
func ResolvConfManaged(data []byte) bool { return strings.HasPrefix(string(data), dnsHeader) }

func (s *Service) DNSStatus(ctx context.Context) (DNS, error) {
	rc, err := s.Runner.ReadFile(ResolvConfPath)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return DNS{}, fmt.Errorf("read %s: %w", ResolvConfPath, err)
	}
	active, _ := system.ServiceActive(ctx, s.Runner, ResolvedUnit)
	if !active || !usesResolved(rc) {
		return DNS{Servers: nameservers(rc), Managed: ResolvConfManaged(rc)}, nil
	}
	d := DNS{Resolved: true}
	if data, err := s.Runner.ReadFile(ResolvedDropIn); err == nil {
		d.Managed, d.Servers = true, resolvedServers(data)
		return d, nil
	}
	// "Global: 1.1.1.1" and "Link 2 (eth0): 8.8.8.8 ..." lines.
	res, err := s.Runner.Query(ctx, "resolvectl", "dns")
	if err == nil {
		for _, line := range strings.Split(res.Stdout, "\n") {
			if _, v, ok := strings.Cut(line, ":"); ok {
				for _, f := range strings.Fields(v) {
					if !slices.Contains(d.Servers, f) {
						d.Servers = append(d.Servers, f)
					}
				}
			}
		}
	}
	return d, nil
}

// SetDNS points the system at servers: a systemd-resolved drop-in when
// the system uses it, /etc/resolv.conf otherwise. resolv.conf may be
// rewritten later by DHCP, cloud-init or resolvconf.
func (s *Service) SetDNS(ctx context.Context, servers []string) error {
	if len(servers) == 0 || len(servers) > MaxDNSServers {
		return ErrDNSServers
	}
	d, err := s.DNSStatus(ctx)
	if err != nil {
		return err
	}
	var f change.File
	if d.Resolved {
		if err := s.Runner.MkdirAll(dirOf(ResolvedDropIn), 0o755); err != nil {
			return fmt.Errorf("create %s: %w", dirOf(ResolvedDropIn), err)
		}
		f = change.File{Path: ResolvedDropIn, Data: ResolvedConfig(servers), Mode: 0o644}
	} else {
		old, err := s.Runner.ReadFile(ResolvConfPath)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("read %s: %w", ResolvConfPath, err)
		}
		f = change.File{Path: ResolvConfPath, Data: ResolvConf(old, servers), Mode: 0o644}
	}
	return s.applyDNS(ctx, f)
}

// ResetDNS removes LiteNode's systemd-resolved drop-in, so the servers
// from the system configuration and DHCP apply again. resolv.conf has no
// such default: the user picks servers instead.
func (s *Service) ResetDNS(ctx context.Context) error {
	return s.applyDNS(ctx, change.File{Path: ResolvedDropIn, Remove: true})
}

func (s *Service) applyDNS(ctx context.Context, f change.File) error {
	_, err := s.Changes.Apply(ctx, change.Change{Parts: []change.Part{{Kind: DNSKind(), Files: []change.File{f}}}})
	return err
}

func dirOf(path string) string { return path[:strings.LastIndex(path, "/")] }

// DNSKind is the "dns" configuration kind. Apply restarts
// systemd-resolved when it runs, so it reads its configuration again;
// resolv.conf needs nothing.
func DNSKind() *change.Kind {
	return &change.Kind{
		Name: "dns",
		Apply: func(ctx context.Context, r system.Runner) error {
			if active, _ := system.ServiceActive(ctx, r, ResolvedUnit); !active {
				return nil
			}
			if err := system.Systemctl(ctx, r, "restart", ResolvedUnit); err != nil {
				return err
			}
			return nil
		},
	}
}

// DNSProber tests whether a DNS server answers.
type DNSProber func(ctx context.Context, server string) error

// ProbeDNS looks up a well-known name directly at server (UDP, 3
// seconds), bypassing the system configuration.
func ProbeDNS(ctx context.Context, server string) error {
	ctx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()
	r := &net.Resolver{PreferGo: true, Dial: func(ctx context.Context, network, _ string) (net.Conn, error) {
		var d net.Dialer
		return d.DialContext(ctx, network, net.JoinHostPort(server, "53"))
	}}
	_, err := r.LookupHost(ctx, dnsProbeName)
	return err
}

// LookupWorks reports whether the system resolver can look up a
// well-known name, after a DNS change.
func (s *Service) LookupWorks(ctx context.Context) bool {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	_, err := s.Runner.Query(ctx, "getent", "hosts", dnsProbeName)
	return err == nil
}
